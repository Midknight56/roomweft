CREATE TABLE IF NOT EXISTS product_searches (
 key TEXT PRIMARY KEY, query TEXT NOT NULL, max_price INTEGER NOT NULL,
 result_ids TEXT NOT NULL, body TEXT NOT NULL, retrieved_at INTEGER NOT NULL, expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS counters (key TEXT PRIMARY KEY, day TEXT NOT NULL, n INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS designs (
 id TEXT PRIMARY KEY, visitor TEXT NOT NULL, version INTEGER NOT NULL, body TEXT NOT NULL,
 created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);
